"""Generate immutable v2 C data from the reviewed metadata manifest.
Never change a released manifest in place: add a new dataset version instead.
No imagery bytes are bundled or written to SD by this generator.
"""
import hashlib,json,pathlib
root=pathlib.Path(__file__).resolve().parents[1]
p=root/'docs/datasets/streetguess-v2.json'
raw=p.read_bytes();data=json.loads(raw)
assert data['version']==2 and 5<=len(data['locations'])<=256
q=lambda s:json.dumps(s,ensure_ascii=True)
lines=['/* Generated by tools/generate_challenge_dataset.py. See manifest for credits. */','#include "guess_challenge.h"',f'const uint32_t guess_dataset_id=0x{hashlib.sha256(raw).hexdigest()[:8]}u;','const GuessLocation guess_locations[]={']
for x in data['locations']:
 assert x['license'] in ['etalab-2.0','cc-by-4.0','cc-by-sa-4.0'] and len(x['id'])==36
 strings=[x[k] for k in ['id','country','name','hint','license','credit','metadata_url']]
 lines.append(' {'+','.join(q(s) for s in strings)+f",{x['lat']:.9f},{x['lon']:.9f},{str(x.get('landmark',False)).lower()}"+'},')
lines+=['};','const unsigned guess_location_count=sizeof(guess_locations)/sizeof(guess_locations[0]);']
(root/'source/guess_locations.c').write_text('\n'.join(lines)+'\n')
print(f"Generated {len(data['locations'])} stable locations, dataset {hashlib.sha256(raw).hexdigest()[:8]}")
